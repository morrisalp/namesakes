"""Align generated faces and embed them with ArcFace.

For each name generated by generate_faces.py, writes:
    output/aligned/{model}/{name}/{i}.png                 aligned generations
    output/aligned/{model}/{name}/perturbed/{i}.png    aligned perturbed-name generations
    output/cached_embeds/{model}/{name}/af.pt             ArcFace embeddings (k x 512)
    output/cached_embeds/{model}/{name}/af_gt.pt          embedding of the reference photo
    output/cached_embeds/{model}/{name}/af_perturbed.pt

Usage:
    uv run src/postprocess.py model=sdxl
"""
import argparse
import sys

# Hydra's LazyCompletionHelp doesn't support Python 3.14's argparse _check_help;
# tolerate non-string help values.
if sys.version_info >= (3, 14) and hasattr(argparse.ArgumentParser, "_check_help"):
    _orig_check_help = argparse.ArgumentParser._check_help
    def _safe_check_help(self, action):
        if not isinstance(action.help, str):
            return
        _orig_check_help(self, action)
    argparse.ArgumentParser._check_help = _safe_check_help

import os
from pathlib import Path

import hydra
import torch
from omegaconf import DictConfig
from PIL import Image
from tqdm.auto import tqdm

from alignment import FaceAligner
from arcface_model import ArcFaceModel


def get_model_name_slug(model_path):
    """Extract a directory-safe name from a model file path"""
    return Path(model_path).stem.replace('.', '_')


def align_and_save(aligner, imgs, out_dir):
    aligned = [aligner.align(img) for img in imgs]
    os.makedirs(out_dir, exist_ok=True)
    for i, img in enumerate(aligned):
        img.save(os.path.join(out_dir, f"{i}.png"))
    return aligned


@hydra.main(version_base=None, config_path="../config", config_name="config")
@torch.no_grad()
def main(cfg: DictConfig):
    model_id = cfg.model.diffusion_model_path if cfg.model.type == "flux" else cfg.model.checkpoint
    model_slug  = get_model_name_slug(model_id)
    faces_dir   = os.path.join(cfg.output_dir, model_slug)
    aligned_dir = os.path.join(cfg.aligned_dir, model_slug)
    embeds_dir  = os.path.join(cfg.embeds_dir, model_slug)

    if not os.path.isdir(faces_dir):
        print(f"Output directory not found: {faces_dir}\nRun generate_faces.py first.")
        return

    aligner = FaceAligner(cfg.landmark_fn)
    arcface = ArcFaceModel(cfg.arcface_device)

    person_dirs = sorted(p for p in Path(faces_dir).iterdir() if p.is_dir())
    print(f"Found {len(person_dirs)} person directories in {faces_dir}")

    for person_dir in tqdm(person_dirs):
        name = person_dir.name
        image_files = sorted(person_dir.glob("*.png"))
        if not image_files:
            continue
        imgs = [Image.open(f).convert("RGB") for f in image_files]
        person_aligned_dir = os.path.join(aligned_dir, name)
        try:
            aligned = align_and_save(aligner, imgs, person_aligned_dir)
        except UnboundLocalError:
            print(f"Warning: alignment failed for {name}, skipping")
            continue

        # Reference photo (already aligned by data_prep, or raw as a fallback)
        gt_img = None
        for fn in ("gt_aligned.jpg", "gt_raw.jpg"):
            if (person_dir / fn).exists():
                gt_img = Image.open(person_dir / fn).convert("RGB")
                break

        # Perturbed-name generations
        d_imgs = None
        pert_dirs = list(person_dir.glob("perturbed-*"))
        if pert_dirs:
            d_files = sorted(pert_dirs[0].glob("*.png"))
            if d_files:
                d_imgs = [Image.open(f).convert("RGB") for f in d_files]
                try:
                    d_imgs = align_and_save(aligner, d_imgs,
                                            os.path.join(person_aligned_dir, "perturbed"))
                except Exception:
                    pass  # keep raw images if alignment fails

        person_embeds_dir = os.path.join(embeds_dir, name)
        os.makedirs(person_embeds_dir, exist_ok=True)
        torch.save(arcface.embed_imgs(aligned), os.path.join(person_embeds_dir, "af.pt"))
        if gt_img is not None:
            torch.save(arcface.embed_imgs([gt_img]), os.path.join(person_embeds_dir, "af_gt.pt"))
        if d_imgs is not None:
            torch.save(arcface.embed_imgs(d_imgs), os.path.join(person_embeds_dir, "af_perturbed.pt"))


if __name__ == "__main__":
    main()
